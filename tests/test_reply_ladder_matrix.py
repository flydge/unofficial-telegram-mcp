"""0.58 criteria 2 and 4: every reply source keeps its 0.57 projection, display, authority and preview, except the
listed flips, each of which only admits a source 0.57 refused.

`fixtures/reply_ladder_matrix_0_57.json` was generated by `reply_ladder_matrix.py` at the 0.57 tip (f2239c4),
before the ladder table, and is pinned here by its full sha256; it is never regenerated. The rows are recomputed
from the code under test; every row outside flips() must be byte-identical to its frozen row.
"""
import hashlib
import json
import unittest

from reply_ladder_matrix import COLUMNS, FIXTURE, rows, serialize

FIXTURE_SHA256 = '12b3bc0f78b5a6f3c512f0188499725bb6ac9fa710b75f80cde69b0e3972bf7b'
FIXTURE_ROWS = 6098
MEDIA = ('document', 'photo', 'voice_note')
TEXT_URL_REASON = 'v24: a document, photo or voice-note caption with a TextUrl (0.58 part 2, work item 3)'
EMOJI_REASON = 'v25/v26: a CustomEmoji with a decimal-string id over exactly one emoji (0.58 part 2, work item 4)'
STAMP_REASON = 'v28: a voice-note caption timestamp within the duration, on its whole token (0.58 part 2, work item 5)'


def flips(labels) -> dict[str, tuple[int, str]]:
    """The 0.57 rows 0.58 deliberately admits, each with the version it now selects and its reason (criterion 4).
    The ladder slice itself flipped nothing (criterion 2). Integer custom emoji ids, timestamps beyond the voice note's
    duration and every timestamp outside a voice note stay refused, so they are not here."""
    result = {}
    for label in labels:
        group, kind, case, *_ = label.split('/') + ['']
        if group in ('subset', 'dirty', 'topic') and kind in MEDIA and 'T' in case:
            result[label] = (24, TEXT_URL_REASON)
        elif group == 'probe' and case in ('custom_emoji_string', 'custom_emoji_styled'):
            result[label] = (26 if kind in MEDIA else 25, EMOJI_REASON)
        elif group == 'probe' and kind == 'voice_note' and case in ('media_timestamp', 'media_timestamp_styled'):
            result[label] = (28, STAMP_REASON)
    return result


# Only these rows may differ from the frozen matrix; their count per reason is pinned so a rule edit is visible.
FLIP_COUNTS = {TEXT_URL_REASON: 3 * (2 ** 7 * 5 + 2), EMOJI_REASON: 8, STAMP_REASON: 2}
STAY_REFUSED = ('custom_emoji_integer', 'media_timestamp_beyond_duration')


class ReplyLadderMatrixTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = FIXTURE.read_bytes()
        cls.frozen = json.loads(cls.data)['rows']
        cls.current = rows()

    def test_the_frozen_matrix_is_the_pinned_0_57_characterization(self):
        # Break: an edited or regenerated freeze would hide drift instead of catching it.
        self.assertEqual(hashlib.sha256(self.data).hexdigest(), FIXTURE_SHA256)
        self.assertEqual(tuple(json.loads(self.data)['columns']), COLUMNS)
        self.assertEqual(len(self.frozen), FIXTURE_ROWS)
        self.assertEqual(serialize(self.frozen), self.data)
        accepted = [row for row in self.frozen if row[1] is not None]
        self.assertEqual({row[1] for row in accepted}, set(range(1, 24)))
        self.assertTrue(all(row[3] is (row[1] % 2 == 0) for row in accepted))
        self.assertTrue(all(row[8] == [] for row in accepted))
        self.assertTrue(all(row[1:] == [None] * 8 for row in self.frozen if row[1] is None))
        self.assertTrue(all(row[1] is None for row in self.frozen if row[0].startswith('probe/')))

    def test_every_0_57_source_is_unchanged_except_the_listed_flips(self):
        # Break: a 0.58 family changes any v1-v23 version, authority, display, preview or forged-version refusal,
        # or admits a probe criterion 4 keeps refused.
        frozen = {row[0]: row for row in self.frozen}
        current = {row[0]: row for row in self.current}
        self.assertEqual(sorted(set(frozen) - set(current)), [])
        listed = flips(frozen)
        changed = sorted(label for label in frozen if current[label] != frozen[label])
        self.assertEqual(changed[:20], sorted(listed)[:20])
        self.assertEqual(changed, sorted(listed))
        counts = {}
        for label, (version, reason) in listed.items():
            counts[reason] = counts.get(reason, 0) + 1
            with self.subTest(label=label):
                # A flip only admits: the frozen row refused, the current row selects the listed version and parity,
                # needs reply_media_targets exactly when it is media, and accepts no forged version.
                self.assertEqual(frozen[label][1:], [None] * 8)
                self.assertEqual(current[label][1], version)
                self.assertIs(current[label][3], version % 2 == 0)
                self.assertEqual(current[label][2].split()[0] == 'media', version % 2 == 0)
                self.assertEqual(current[label][8], [])
        self.assertEqual(counts, FLIP_COUNTS)
        for label in frozen:
            if label.startswith('probe/') and label.split('/')[2] in STAY_REFUSED:
                self.assertEqual(current[label][1:], [None] * 8, label)
        for kind in ('text', 'document', 'photo'):
            for case in ('media_timestamp', 'media_timestamp_styled'):
                self.assertEqual(current[f'probe/{kind}/{case}'][1:], [None] * 8)
        unchanged = [row for row in self.current if row[0] not in listed]
        self.assertEqual(serialize(unchanged), serialize([row for row in self.frozen if row[0] not in listed]))


if __name__ == '__main__':
    unittest.main()
