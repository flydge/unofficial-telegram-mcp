"""0.58 criterion 2: every reply source keeps its 0.57 projection, display, authority and preview.

`fixtures/reply_ladder_matrix_0_57.json` was generated by `reply_ladder_matrix.py` at the 0.57 tip (f2239c4),
before the ladder table, and is pinned here by its full sha256; it is never regenerated. The rows are recomputed
from the code under test and must serialize to the same bytes.
"""
import hashlib
import json
import unittest

from reply_ladder_matrix import COLUMNS, FIXTURE, rows, serialize

FIXTURE_SHA256 = '12b3bc0f78b5a6f3c512f0188499725bb6ac9fa710b75f80cde69b0e3972bf7b'
FIXTURE_ROWS = 6098
# 0.57 rows a later 0.58 slice deliberately changes, each label with its reason. A flip may only admit a source
# 0.57 refused (criterion 4); the ladder slice itself flips nothing (criterion 2).
FLIPS: dict[str, str] = {}


class ReplyLadderMatrixTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = FIXTURE.read_bytes()
        cls.frozen = json.loads(cls.data)['rows']
        cls.current = rows()

    def test_the_frozen_matrix_is_the_pinned_0_57_characterization(self):
        # Break: an edited or regenerated freeze would hide drift instead of catching it.
        self.assertEqual(hashlib.sha256(self.data).hexdigest(), FIXTURE_SHA256)
        self.assertEqual(tuple(json.loads(self.data)['columns']), COLUMNS)
        self.assertEqual(len(self.frozen), FIXTURE_ROWS)
        self.assertEqual(serialize(self.frozen), self.data)
        accepted = [row for row in self.frozen if row[1] is not None]
        self.assertEqual({row[1] for row in accepted}, set(range(1, 24)))
        self.assertTrue(all(row[3] is (row[1] % 2 == 0) for row in accepted))
        self.assertTrue(all(row[8] == [] for row in accepted))
        self.assertTrue(all(row[1:] == [None] * 8 for row in self.frozen if row[1] is None))
        self.assertTrue(all(row[1] is None for row in self.frozen if row[0].startswith('probe/')))

    def test_every_0_57_source_is_unchanged_except_the_listed_flips(self):
        # Break: the ladder table changes any version, authority, display, preview or forged-version refusal.
        frozen = {row[0]: row for row in self.frozen}
        current = {row[0]: row for row in self.current}
        self.assertEqual(sorted(set(frozen) - set(current)), [])
        changed = sorted(label for label in frozen if current[label] != frozen[label])
        self.assertEqual(changed[:20], sorted(FLIPS)[:20])
        self.assertEqual(changed, sorted(FLIPS))
        self.assertTrue(all(frozen[label][1] is None for label in FLIPS))
        if not FLIPS:
            self.assertEqual(serialize(self.current), self.data)


if __name__ == '__main__':
    unittest.main()
