"""Generate the kit's Install.command with the release pins embedded (CLIENTS-8).

Development host only; stdlib only. The release build renders one Install.command per kit: the seed
sha256 and bytes and the trusted index sha256 are literals in the script, never read from the kit at
install time. Double-clicked in Finder it runs in native Terminal:
`/usr/bin/env -i /bin/sh -p bootstrap.sh` from its own directory with those pins (bootstrap.sh itself is
covered by the DMG's signature, not by a pin here), then the activation command that
the installer printed, `connect`, inline in the same Terminal, so the QR page opens and the final
result prints there. It accepts exactly the results the installer returns for a kit. After a first install
(`activation_required` with installation `installed`, or `reused` on a repeat) the activation argv must be
exactly the installed release's python3 with -I -S -B, its launcher.py and `connect`, under
`.../releases/<index sha256>`. After an upgrade or its repeat (`upgraded` with installation `upgraded` or
`reused`), or the repeat of the release a finished rollback went back to (`rolled_back` with installation
`reused`), the same `connect` runs from that `release_root`, which must be this kit's release; with a ready
session it reports `already_connected`. Any other status or installation refuses. bootstrap.sh gets no `--claude-code`, so an upgrade keeps the installed mode. `--prepare-only`
stops after verification. Every refusal prints one fixed code.

The release build calls `render_pins` with the kit's release-pins.json bytes (release_pins.py, the one
schema the plugin's bin/install reads too), so the embedded pins are those bytes' values. When they carry
a Team ID (a Developer ID kit), it is a literal too and bootstrap.sh gets `--seed-team <TEAMID>`, so the
staged seed must satisfy the Developer ID designated requirement before it runs. A published kit without
a Team ID is refused at render time (`team_required`, or `pins_invalid` from the schema); only the
unreleased ad hoc test kit runs without one.

Install.command itself is not code-signed: the DMG's Developer ID signature and stapled ticket cover the
image it ships in. How Gatekeeper treats the double-clicked script is an owner-session observation.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path
import re
import sys

CODES = frozenset({'pins_invalid', 'team_required'})
HASH = re.compile(r'[0-9a-f]{64}')
TEAM = re.compile(r'[0-9A-Z]{10}')
MAX_SEED = 2097152  # bootstrap.sh's --seed-bytes bound
REFUSALS = ('usage', 'kit_unavailable', 'kit_incomplete', 'bootstrap_failed', 'activation_unexpected',
            'activation_failed')
TEMPLATE = r'''#!/bin/sh -p
# Install.command, generated by packaging/install_command.py for one release kit; do not edit.
# Runs bootstrap.sh from this folder with the embedded pins in native Terminal, then the printed activation
# command with `connect` inline: the QR page opens here and the final result prints here. An upgrade
# or a repeat runs the same `connect` from the installed release (already_connected when ready).
set -eu
umask 077
PATH=/usr/bin:/bin:/usr/sbin:/sbin
export PATH
unset CDPATH ENV BASH_ENV
install_seed_sha256=@SEED_SHA256@
install_seed_bytes=@SEED_BYTES@
install_index_sha256=@INDEX_SHA256@
install_seed_team='@SEED_TEAM@'
install_fail() {
    /usr/bin/printf '%s\n' "Install.command stopped: $1. See the install guide." >&2
    /usr/bin/printf '{"schema_version":1,"error_code":"%s"}\n' "$1" >&2
    exit "$2"
}
install_prepare=''
if [ "$#" -eq 1 ] && [ "$1" = --prepare-only ]; then
    install_prepare=yes
elif [ "$#" -ne 0 ]; then
    install_fail usage 2
fi
case "$0" in /*) ;; *) install_fail kit_unavailable 3;; esac
install_kit=$(/usr/bin/dirname "$0") || install_fail kit_unavailable 3
install_kit=$(cd -P "$install_kit" 2>/dev/null && /bin/pwd -P) || install_fail kit_unavailable 3
case "$install_kit" in /*) ;; *) install_fail kit_unavailable 3;; esac
[ "${#install_kit}" -le 1024 ] || install_fail kit_unavailable 3
case "$install_kit" in *'
'*) install_fail kit_unavailable 3;; esac
if /usr/bin/printf '%s' "$install_kit" | /usr/bin/env -i LC_ALL=C /usr/bin/grep -q '[[:cntrl:]]'; then
    install_fail kit_unavailable 3
fi
for install_name in bootstrap.sh bootstrap-verifier release.tar.gz release-index.json; do
    [ -f "$install_kit/$install_name" ] && [ ! -L "$install_kit/$install_name" ] || install_fail kit_incomplete 3
done
set -- --seed "$install_kit/bootstrap-verifier" --seed-sha256 "$install_seed_sha256" \
    --seed-bytes "$install_seed_bytes" --archive "$install_kit/release.tar.gz" \
    --index "$install_kit/release-index.json" --trusted-index-sha256 "$install_index_sha256"
if [ -n "$install_seed_team" ]; then set -- "$@" --seed-team "$install_seed_team"; fi
if [ "$install_prepare" = yes ]; then
    /usr/bin/env -i /bin/sh -p "$install_kit/bootstrap.sh" --prepare-only "$@" || install_fail bootstrap_failed 4
    exit 0
fi
install_result=$(/usr/bin/env -i /bin/sh -p "$install_kit/bootstrap.sh" "$@") || install_fail bootstrap_failed 4
[ "${#install_result}" -le 65536 ] || install_fail activation_unexpected 5
/usr/bin/printf '%s\n' "$install_result"
install_field() {
    /usr/bin/printf '%s' "$install_result" | /usr/bin/env -i /usr/bin/plutil -extract "$1" raw -o - - 2>/dev/null
}
install_status=$(install_field status) || install_fail activation_unexpected 5
install_root=$(install_field release_root) || install_fail activation_unexpected 5
case "$install_root" in /*/releases/"$install_index_sha256") ;; *) install_fail activation_unexpected 5;; esac
case "$install_root" in *//*|*/../*|*/./*) install_fail activation_unexpected 5;; esac
case "$install_root" in *'
'*) install_fail activation_unexpected 5;; esac
if /usr/bin/printf '%s' "$install_root" | /usr/bin/env -i LC_ALL=C /usr/bin/grep -q '[[:cntrl:]]'; then
    install_fail activation_unexpected 5
fi
install_kind=$(install_field installation) || install_fail activation_unexpected 5
# Exactly the results the installer can return for a kit: a first install (installed, or reused on a repeat), an
# upgrade or its repeat, or the repeat of the release a finished rollback went back to.
case "$install_status:$install_kind" in
    activation_required:installed|activation_required:reused|upgraded:upgraded|upgraded:reused|rolled_back:reused) ;;
    *) install_fail activation_unexpected 5;;
esac
case "$install_status" in
    activation_required)
        [ "$(install_field activation_arguments)" = 6 ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.0)" = "$install_root/python/bin/python3" ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.1)" = -I ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.2)" = -S ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.3)" = -B ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.4)" = "$install_root/launcher.py" ] || install_fail activation_unexpected 5
        [ "$(install_field activation_arguments.5)" = connect ] || install_fail activation_unexpected 5
        install_next='Installed. Starting the Telegram login (connect) in this window.';;
    *)
        # An upgrade or a repeat: the installed release is this kit's; connect is the same command.
        install_next='Installation is up to date. Running connect in this window; a ready session reports already_connected.';;
esac
/usr/bin/printf '%s\n' "$install_next"
if /usr/bin/env -i PATH=/usr/bin:/bin:/usr/sbin:/sbin LC_ALL=C "$install_root/python/bin/python3" -I -S -B \
    "$install_root/launcher.py" connect; then
    /usr/bin/printf '%s\n' 'Install.command finished.'
else
    install_fail activation_failed 6
fi
'''


class InstallCommandError(ValueError):
    """One fixed refusal code from CODES."""

    def __init__(self, code):
        super().__init__(code if code in CODES else 'pins_invalid')


def render(*, seed_sha256, seed_bytes, index_sha256, team_id=None, published=False):
    """The Install.command bytes with these pins embedded; `team_id` (release-pins.json's) adds --seed-team."""
    if not (type(seed_sha256) is str and HASH.fullmatch(seed_sha256) and type(index_sha256) is str
            and HASH.fullmatch(index_sha256) and type(seed_bytes) is int and 0 < seed_bytes <= MAX_SEED
            and type(published) is bool and (team_id is None or (type(team_id) is str and TEAM.fullmatch(team_id)))):
        raise InstallCommandError('pins_invalid')
    if published and team_id is None:
        raise InstallCommandError('team_required')
    text = (TEMPLATE.replace('@SEED_SHA256@', seed_sha256).replace('@SEED_BYTES@', str(seed_bytes))
            .replace('@INDEX_SHA256@', index_sha256).replace('@SEED_TEAM@', team_id or ''))
    if re.search(r'@[A-Z0-9_]+@', text):  # every placeholder replaced; "$@" is the script's own
        raise InstallCommandError('pins_invalid')
    return text.encode('ascii')


def _release_pins():
    name = 'install_command_release_pins'
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, Path(__file__).resolve().parent / 'release_pins.py')
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        sys.modules[name] = module
    return sys.modules[name]


def render_pins(data):
    """The Install.command bytes for one kit's release-pins.json bytes, parsed under the one schema."""
    try:
        pins = _release_pins().parse(data)
    except ValueError:
        raise InstallCommandError('pins_invalid') from None
    return render(seed_sha256=pins['seed_sha256'], seed_bytes=pins['seed_bytes'], index_sha256=pins['index_sha256'],
                  team_id=pins['team_id'] or None, published=pins['publication'] == 'published')
